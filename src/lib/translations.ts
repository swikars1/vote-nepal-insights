// Translate addresses - converts administrative terms
export function translateAddress(address: string, toLang: "en" | "np"): string {
  if (!address) return address;
  
  let translated = address;
  const termMap = toLang === "en" ? ADDRESS_TERMS_EN_NP : ADDRESS_TERMS_NP_EN;
  
  // Replace administrative terms
  Object.entries(termMap).forEach(([key, value]) => {
    translated = translated.replace(new RegExp(key, "g"), value);
  });
  
  return translated;
}

