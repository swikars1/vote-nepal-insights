// Utility function to translate text in language context
export function translatePartyName(name: string, toLang: "en" | "np"): string {
  if (!name) return name;
  
  if (toLang === "en") {
    // If it's already a Nepali name, translate it
    if (PARTY_NAMES_EN_NP[name]) {
      return PARTY_NAMES_EN_NP[name];
    }
    // If it's already in English, return as is
    return name;
  } else {
    // If it's already an English name, translate it to Nepali
    if (PARTY_NAMES_NP_EN[name]) {
      return PARTY_NAMES_NP_EN[name];
    }
    // If it's already in Nepali, return as is
    return name;
  }
}

export function translateQualification(name: string, toLang: "en" | "np"): string {
  if (!name) return name;
  
  if (toLang === "en") {
    // Direct lookup
    if (QUALIFICATION_NAMES_EN_NP[name]) {
      return QUALIFICATION_NAMES_EN_NP[name];
    }
    
    // Fuzzy match for partial strings
    for (const [key, value] of Object.entries(QUALIFICATION_NAMES_EN_NP)) {
      if (name.toLowerCase().includes(key.toLowerCase()) || 
          key.toLowerCase().includes(name.toLowerCase())) {
        return value;
      }
    }
    return name;
  } else {
    // Direct lookup
    if (QUALIFICATION_NAMES_NP_EN[name]) {
      return QUALIFICATION_NAMES_NP_EN[name];
    }
    
    // Fuzzy match for partial strings
    for (const [key, value] of Object.entries(QUALIFICATION_NAMES_NP_EN)) {
      if (name.toLowerCase().includes(key.toLowerCase()) || 
          key.toLowerCase().includes(name.toLowerCase())) {
        return value;
      }
    }
    return name;
  }
}

